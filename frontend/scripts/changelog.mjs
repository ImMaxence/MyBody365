// Turns ../CHANGELOG.md into src/app/features/changelog/changelog.data.ts (run before every build,
// test and dev server: see package.json). The page is then prerendered like the rest of the site.
// Supported markdown: "## [version] - date", a paragraph (the summary), "### section", "- item",
// and inline **bold**, `code`, [link](url).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const SOURCE = '../CHANGELOG.md';
const TARGET = 'src/app/features/changelog/changelog.data.ts';
// the version alone: the site footer and the profile show it without loading every release
const VERSION_TARGET = 'src/app/features/changelog/changelog.version.ts';

if (!existsSync(SOURCE)) {
  console.warn(`changelog: ${SOURCE} not found, ${TARGET} left as it is`);
  process.exit(0);
}

/** "**a** and `b`" → [{ t: 'a', b: true }, { t: ' and ' }, { t: 'b', c: true }] */
function inline(text) {
  const out = [];
  const re = /\*\*(.+?)\*\*|`(.+?)`|\[(.+?)\]\((https?:\/\/[^)\s]+)\)/g;
  let last = 0;
  for (const m of text.matchAll(re)) {
    if (m.index > last) out.push({ t: text.slice(last, m.index) });
    if (m[1]) out.push({ t: m[1], b: true });
    else if (m[2]) out.push({ t: m[2], c: true });
    else out.push({ t: m[3], href: m[4] });
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push({ t: text.slice(last) });
  return out;
}

const lines = readFileSync(SOURCE, 'utf8').replace(/\r/g, '').split('\n');
const intro = [];
const releases = [];
let release = null;
let section = null;
for (const raw of lines) {
  const line = raw.trimEnd();
  let m;
  if ((m = line.match(/^## \[(.+?)\](?:\s*-\s*(\d{4}-\d{2}-\d{2}))?/))) {
    release = { version: m[1], date: m[2] ?? null, summary: [], sections: [] };
    releases.push(release);
    section = null;
  } else if ((m = line.match(/^### (.+)/)) && release) {
    section = { title: m[1].trim(), items: [] };
    release.sections.push(section);
  } else if ((m = line.match(/^\s*[-*] (.+)/)) && section) {
    section.items.push(inline(m[1].trim()));
  } else if (line.trim() && !line.startsWith('#')) {
    if (section && raw.startsWith('  ') && section.items.length) {
      // continuation of the previous item
      section.items[section.items.length - 1].push({ t: ' ' + line.trim() });
    } else if (release && !section) {
      release.summary.push(...inline((release.summary.length ? ' ' : '') + line.trim()));
    } else if (!release) {
      intro.push(...inline((intro.length ? ' ' : '') + line.trim()));
    }
  }
}

const current = releases.find((r) => /^\d+\.\d+\.\d+/.test(r.version))?.version ?? '0.0.0';
const body = `// Generated by scripts/changelog.mjs from CHANGELOG.md — do not edit by hand.
import type { Release, Segment } from './changelog.model';

export { CURRENT_VERSION } from './changelog.version';

export const INTRO: Segment[] = ${JSON.stringify(intro)};

export const RELEASES: Release[] = ${JSON.stringify(releases, null, 2)};
`;
writeFileSync(TARGET, body);
writeFileSync(
  VERSION_TARGET,
  `// Generated by scripts/changelog.mjs from CHANGELOG.md — do not edit by hand.
export const CURRENT_VERSION = ${JSON.stringify(current)};
`,
);
console.log(`changelog: ${releases.length} release(s), current ${current}`);
